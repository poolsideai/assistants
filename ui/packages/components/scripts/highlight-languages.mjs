// Regenerate after a Shiki update; this manifest contains names, never loaders.
import { readFileSync, writeFileSync } from "node:fs";
import { bundledLanguages } from "shiki/langs";

const target = new URL("../src/lib/components/assistant-ui/highlightLanguages.ts", import.meta.url);
const output = `// Generated by scripts/highlight-languages.mjs from Shiki's complete registry.\n// Keep every optional grammar and alias without importing its loader on the UI thread.\nexport const highlightLanguages = new Set([\n${Object.keys(
  bundledLanguages,
)
  .sort()
  .map((name) => `  ${JSON.stringify(name)},`)
  .join("\n")}\n]);\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Regenerate highlightLanguages.ts");
} else writeFileSync(target, output);
