export function acpSessionWorkspacePath(
  appState: Pick<AppState, "environment">,
  workspaceFolders: WorkspaceFolder[],
  fallbackPath: string,
  isChat: boolean,
): string {
  return isChat
    ? ACP_CHAT_WORKSPACE_PATH
    : acpWorkspacePath(appState, workspaceFolders, fallbackPath);
}

