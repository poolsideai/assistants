        exitCode === undefined
          ? `Teardown script did not run: ${command}`
          : `Teardown script exited with code ${exitCode}: ${command}`;
      const tail = outputTail.trim().split("\n").slice(-TEARDOWN_OUTPUT_TAIL_LINES).join("\n");
      throw new Error(tail ? `${detail}\n${tail}` : detail);
